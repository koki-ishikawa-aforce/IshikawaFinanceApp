-- 適用順序（この移行は片方向のみ安全）: 先に #572 のコードをデプロイし、その後に本移行を適用する。
-- 逆順にすると、旧コードのマスタ削除リマップ（カテゴリ削除・経費種別削除に伴う学習ルールの付け替え）が
-- 条件無しで本テーブルを引くため relation does not exist で落ちる。このハンドラーは例外を伝播させる
-- 設計（safeSubscribe を使わない）で、しかも取引と加盟店学習ルールを付け替えた後・完了通知の発行前に
-- 落ちるため、「取引と加盟店ルールは移動先に付け替わっているのに削除要請だけが remap_failed で止まり、
-- マスタは残る」という食い違った状態になる。同じ窓では旧 API の GET /api/classification/amazon-rules も
-- 500 になる。
-- 誤って先に適用した場合は、コード配布後に同じ削除操作をやり直せば復旧する（リマップは対象 ID を
-- 移動先 ID へ書き換える操作で、既に移動済みの行は 0 件になるため二重適用にならない）。
DROP TABLE "amazon_product_key_learning_rules" CASCADE;
