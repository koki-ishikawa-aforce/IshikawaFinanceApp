-- ここから上のコメントのみ手書きで、適用順序の注意を残すために追記した（0009 と同じ形式）。
--
-- 背景（#391 / #572）: X-1（Amazon 商品キー学習）の取り下げにより、学習ルールの置き場である
-- amazon_product_key_learning_rules を落とす。書き込み経路（手動分類確定イベントの商品キー分岐）は
-- 本番で一度も通っていないため、失われる行は無い。このテーブルを参照する外部キーも存在しない。
