/**
 * モック起動モードの fixture が「今」として想定している日時と時間帯（#506）。
 *
 * `src/mocks/fixtures.ts` の取引・残高・精算はいずれも 2026 年 7 月のものなので、
 * 画面が別の月を当月として描くと、見出しと中身が食い違う。見た目の自動チェック（VRT）は
 * ここを「今」に固定して撮る（`playwright.config.ts` が読む）。
 *
 * fixture の月を動かすときは、この 2 つの値も一緒に動かす（食い違いは
 * `__tests__/clock.test.ts` が落として知らせる）。
 */

/**
 * VRT の撮影中に画面が「今」として扱う日時。
 *
 * 時刻を正午に置いてあるのは、日付の境界から離すため。深夜の時刻にすると、UTC と JST で
 * 日付が別々になり「時間帯を固定し忘れた環境でだけ 1 日ずれる」事故が起きる。
 */
export const MOCK_NOW = '2026-07-24T12:00:00+09:00'

/** {@link MOCK_NOW} が属する月（JST）。月指定が無い・壊れているときに fixture が返す月 */
export const MOCK_DEFAULT_MONTH = '2026-07'

/**
 * VRT の撮影中に固定する時間帯。日付の表示自体は端末の時間帯によらず JST になる(#639)が、
 * 実行環境をあえて揃えておくことで、CI（UTC）と手元（JST）で違う基準画像ができる事故を
 * 構造的に防ぐ(ユニットテストの `vitest.config.ts` と同じ理由・同じ値)。
 */
export const MOCK_TIMEZONE = 'Asia/Tokyo'
